// Fills the range with a header row followed by rows with a label and
// numbers, e.g. for a chart or a table.
void FillTable(ExcelTestWorkbook& book, const wxString& address)
{
    wxExcelRange range = book.GetRange(address);
    const long rows = range.GetRows().GetCount();
    const long columns = range.GetColumns().GetCount();
    REQUIRE(range);

    for ( long row = 1; row <= rows; ++row )
    {
        for ( long column = 1; column <= columns; ++column )
        {
            wxExcelRange cell = range.GetItem(row, &column);
            REQUIRE(cell);

            wxVariant value;
            if ( row == 1 )
                value = wxString::Format("Column%ld", column);
            else if ( column == 1 )
                value = wxString::Format("Row%ld", row - 1);
            else
                value = static_cast<double>(row * 10 + column);

            cell.SetValue(value);
            REQUIRE(cell);
        }
    }
}

