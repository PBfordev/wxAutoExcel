// Each test creates objects in a state where their getters can be used and
// calls every getter which takes no arguments, checking that the call
// succeeded. This finds wrappers using a wrong member name, return type or
// argument, which make the getter always fail. The values returned are not
// checked. The getter lists are generated by tools/generate_getter_lists.py,
// which also lists the getters which cannot be checked and why.

